// One-off build-time generator: turns the public-domain Natural Earth
// country outline for Indonesia (via the `world-atlas` topojson package)
// into a plain SVG path string + a lat/lon -> x/y projector fitted to the
// same viewBox, so the dashboard's risk-map card can render an accurate
// country silhouette with ZERO mapping-library runtime dependency (no
// d3-zoom/d3-color transitively pulled into the browser bundle, no extra
// vuln surface - see the "no react-simple-maps" note in the risk map
// component). Re-run this script only if the target viewBox size changes;
// output is copy-pasted into indonesiaMapData.js.
//
//   node scripts/gen-indonesia-map.mjs
//
import { feature } from 'topojson-client';
import { geoMercator, geoPath } from 'd3-geo';
import worldAtlas from 'world-atlas/countries-110m.json' with { type: 'json' };
import { writeFileSync } from 'fs';

const VIEWBOX = { width: 560, height: 240 };

const geo = feature(worldAtlas, worldAtlas.objects.countries);
const indonesia = geo.features.find((f) => f.properties?.name === 'Indonesia');
if (!indonesia) {
  console.error('Indonesia feature not found in world-atlas dataset.');
  process.exit(1);
}

const projection = geoMercator().fitSize([VIEWBOX.width, VIEWBOX.height], indonesia);
const path = geoPath(projection);
const d = path(indonesia);

// A few named locations used as risk-map markers/popups in the UI. Lat/lon
// pulled from public knowledge of each city's approximate coordinates.
const markers = {
  'Jawa Barat (Bandung)': [107.6191, -6.9175],
  'Sumatera (Medan)': [98.6722, 3.5952],
  'Kalimantan (Pontianak)': [109.3425, -0.0263],
  'Sulawesi (Makassar)': [119.4221, -5.1477],
  'Papua (Jayapura)': [140.7181, -2.5337],
};

const projected = Object.fromEntries(
  Object.entries(markers).map(([name, lonlat]) => [name, projection(lonlat).map((n) => Math.round(n * 10) / 10)])
);

const out = `// AUTO-GENERATED by scripts/gen-indonesia-map.mjs - do not hand-edit.
// Source: Natural Earth country outlines via the world-atlas topojson
// package (countries-110m, public domain), projected with d3-geo
// (geoMercator, fitSize) at build time. No mapping library ships to the
// browser - this file is a plain string + numbers.
export const viewBox = ${JSON.stringify(VIEWBOX)};
export const indonesiaPath = ${JSON.stringify(d)};
export const markers = ${JSON.stringify(projected, null, 2)};
`;

writeFileSync(new URL('../dashboard/src/components/indonesiaMapData.js', import.meta.url), out);
console.log('Wrote dashboard/src/components/indonesiaMapData.js');
console.log('path length:', d.length, 'chars');
